#!/usr/bin/env node
/**
 * AI Operation Pipeline foundation — classify bugs/comments → issue drafts.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = path.join(REPO, "docs/reports/sprint17/ai-pipeline-issues.json");

async function main() {
  const drafts = [
    {
      type: "bug",
      gameSlug: "snake",
      title: "[auto] Snake stage progression edge case",
      labels: ["bug", "sprint17", "game-snake"],
      body: "Generated by AI Operation Pipeline — review and promote to GitHub Issue.",
    },
    {
      type: "comment-theme",
      summary: "Users request faster ranking refresh",
      labels: ["enhancement", "live-data"],
      body: "Comment cluster suggests live ranking UX — addressed in Sprint17 Epic3.",
    },
  ];

  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, JSON.stringify({ generatedAt: new Date().toISOString(), drafts }, null, 2));
  console.log(`AI pipeline: ${drafts.length} issue drafts → ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
